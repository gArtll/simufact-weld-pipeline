"""Comparison figures of the explicit transition mesh, written to docs/images/ as PNG.

Three figures, all built by running the repository's own code -- nothing is drawn by hand:

  transition_templates.png        the two templates themselves (mesh_transition/templates.py), 2->1 pair and 3->1
  transition_vs_unstructured.png  the same fine-to-coarse region filled with the templates and, for comparison,
                                filled automatically: a Delaunay triangulation of the same boundary nodes merged
                                into quadrilaterals where the shape allows, which is how a quad-dominant automatic
                                mesher fills it -- irregular quads, leftover triangles, sliver corners
  graded_vs_uniform.png           a weld region graded away from the seam with the templates, against the same region
                                meshed at the weld size throughout: the element count the grading saves

Every shape number printed on the figures comes from `mesh_transition.quality` (quads) or from the same angle
definition applied to triangles, computed here at draw time.

Needs matplotlib, which the pipeline itself does not: these figures are regenerated by hand, not in CI.

Usage: python tools/make_mesh_figures.py [out_dir]"""
import io
