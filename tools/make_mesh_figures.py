# ---------------------------------------------------------------- figure 2: templates vs automatic fill
def merge_to_quads(tris):
    """Greedily merge adjacent triangle pairs into quadrilaterals, best shape first.

    This is what a quad-dominant automatic mesher does with a triangulation: most pairs become quadrilaterals, the
    ones that would fold stay triangles, and the result is irregular because the triangulation was."""
    def key(a, b):
        return tuple(sorted((tuple(round(v, 9) for v in a), tuple(round(v, 9) for v in b))))

    edges = {}
    for i, t in enumerate(tris):
        for k in range(3):
            edges.setdefault(key(t[k], t[(k + 1) % 3]), []).append((i, k))
    cand = []
    for e, uses in edges.items():
        if len(uses) != 2:
            continue
        (i, ki), (j, kj) = uses
        a, b = tris[i][ki], tris[i][(ki + 1) % 3]
        quad = [a, tris[j][(kj + 2) % 3], b, tris[i][(ki + 2) % 3]]
        sine = min_corner_sine(quad)
        if sine > 0.02:                                      # a pair that would fold stays two triangles
            cand.append((-sine, i, j, quad))
    used, out = set(), []
    for _, i, j, quad in sorted(cand, key=lambda c: c[0]):
        if i in used or j in used:
            continue
        used.update((i, j))
        out.append(quad)
    out += [t for i, t in enumerate(tris) if i not in used]
    return out


def unstructured_fill(boundary_fine, boundary_coarse, seed=7):
    """The band between a fine and a coarse boundary row, meshed automatically instead of with a template:
    Delaunay triangulation of the same boundary nodes plus a few interior points, then merged to quads."""
    import random

    import numpy as np
    from scipy.spatial import Delaunay
    rnd = random.Random(seed)
    pts = [tuple(p) for p in boundary_fine] + [tuple(p) for p in boundary_coarse]
    y0, y1 = boundary_coarse[0][1], boundary_fine[0][1]
    x0, x1 = min(p[0] for p in pts), max(p[0] for p in pts)
    for _ in range(9):                                       # a few interior points, as a paver would place them
        pts.append((x0 + (x1 - x0) * rnd.uniform(0.06, 0.94), y0 + (y1 - y0) * rnd.uniform(0.25, 0.75)))
    P = np.array(pts)
    tri = Delaunay(P)
    tris = []
    for sx in tri.simplices:
        q = [tuple(P[i]) for i in sx]
        cx, cy = sum(v[0] for v in q) / 3.0, sum(v[1] for v in q) / 3.0
        if min(y0, y1) - 1e-9 <= cy <= max(y0, y1) + 1e-9 and x0 - 1e-9 <= cx <= x1 + 1e-9:
            if abs(sum(q[k][0] * q[(k + 1) % 3][1] - q[(k + 1) % 3][0] * q[k][1] for k in range(3)) / 2.0) > 1e-9:
                tris.append(q)
    return merge_to_quads(tris)


def fig_vs_unstructured(out):
    h, height = 1.0, 2.0
    m, _ = strip([2, 2, 3, 3], h=h, height=height)            # 10 fine edges -> 4 coarse, the repository's own row
    tpl = mesh_cells(m)
    xs = [p[0] for c in tpl for p in c]
    x0, x1 = min(xs), max(xs)
    fine_row = [(x0 + k * h, height) for k in range(int(round((x1 - x0) / h)) + 1)]
    coarse_x = sorted({round(p[0], 9) for c in tpl for p in c if abs(p[1]) < 1e-9})
    auto = unstructured_fill(fine_row, [(x, 0.0) for x in coarse_x])

    fig, axes = plt.subplots(2, 1, figsize=(9.4, 5.8))
    fig.suptitle("One fine-to-coarse row: explicit templates, and the same row filled automatically",
                 fontsize=14, fontweight="bold", y=0.985)
    fig.text(0.5, 0.905, "Same region, same boundary nodes: 10 fine edges above, 4 coarse edges below.",
             ha="center", fontsize=9.5, color=MUTED)
    for ax, (title, cells, tone) in zip(axes, (("With the templates  (this tool)", tpl, GOOD),
                                               ("Filled automatically: triangulated, then merged to quads", auto, BAD))):
        fills = [tone if (len(p) == 3 or min_corner_sine(p) < 0.35) else FINE for p in cells]
        draw_cells(ax, cells, fills=fills, lw=1.2, title=title)
        caption(ax, fmt(stats(cells)), y=-0.04)
    fig.text(0.5, 0.02, "Shaded: triangles, and quadrilaterals whose smallest corner sine is below 0.35 "
                        "(a corner past about 160\u00b0 or under 20\u00b0). The template row has neither.",
             ha="center", fontsize=9, color=MUTED)
    fig.subplots_adjust(top=0.845, bottom=0.12, hspace=0.78)
    return save(fig, os.path.join(out, "transition_vs_unstructured.png"))


# ---------------------------------------------------------------- figure 3: graded against uniform
def grid(x_edges, y_edges, m=None):
    m = m or Mesh()
    for j in range(len(y_edges) - 1):
        for i in range(len(x_edges) - 1):
            a = m.node(x_edges[i], y_edges[j])
            b = m.node(x_edges[i + 1], y_edges[j])
            cc = m.node(x_edges[i + 1], y_edges[j + 1])
            d = m.node(x_edges[i], y_edges[j + 1])
            m.quad(a, b, cc, d)
    return m


def graded_region(width=48.0, fine=2.0, bands=((2.0, 4.0), (4.0, 8.0)), fine_rows=2, coarse_rows=3):
    """Fine rows at the weld, two template rows doubling the cell size, coarse rows above."""
    m, y = Mesh(), 0.0
    size = fine
    for _ in range(fine_rows):
        grid([k * size for k in range(int(round(width / size)) + 1)], [y, y + size], m)
        y += size
    for small, big in bands:
        n_fine = int(round(width / small))
        row, _ = strip([2] * (n_fine // 2), h=small, height=big)
        # the template has its fine edges on top and its coarse edge below; here the fine mesh is at the weld,
        # at the bottom, so the row is mirrored in y (and the winding reversed with it, to stay counter-clockwise)
        for q in sorted(row.quads):
            p = [(px, y + (big - py)) for px, py in row.corners(q)][::-1]
            m.quad(*[m.node(*v) for v in p])
        y += big
        size = big
    for _ in range(coarse_rows):
        grid([k * size for k in range(int(round(width / size)) + 1)], [y, y + size], m)
        y += size
    chk = check_all(m)
    if not chk["ok"]:                      # a misplaced row leaves hanging nodes: the figure must not hide that
        raise ValueError("graded region is not a conforming mesh: %s"
                         % {k: (len(v) if isinstance(v, list) else v) for k, v in chk.items()
                            if k in ("hanging_nodes", "non_manifold_edges", "euler_ok", "inverted_elements")})
    return m, y


def fig_graded_vs_uniform(out):
    width, fine = 48.0, 2.0
    g, top = graded_region(width=width, fine=fine)
    u = grid([k * fine for k in range(int(round(width / fine)) + 1)],
             [k * fine for k in range(int(round(top / fine)) + 1)])
    gc, uc = mesh_cells(g), mesh_cells(u)
    fig, axes = plt.subplots(1, 2, figsize=(9.4, 5.2))
    fig.suptitle("The same weld region, graded away from the seam and meshed at the weld size throughout",
                 fontsize=13.5, fontweight="bold", y=0.985)
    fig.text(0.5, 0.93, "%g \u00d7 %g mm, %g mm cells along the weld (bottom edge); grading %g \u2192 %g \u2192 %g mm "
                        "through two template rows." % (width, top, fine, fine, 2 * fine, 4 * fine),
             ha="center", fontsize=9.5, color=MUTED)
    for ax, (title, cells) in zip(axes, (("Graded with the templates", gc), ("Uniform at the weld size", uc))):
        draw_cells(ax, cells, lw=0.7, title=title)
        caption(ax, fmt(stats(cells)), y=-0.04, size=9)
    fig.text(0.5, 0.045, "Same cell size along the weld, same region: %d elements against %d, a factor of %.1f in 2D. "
                         "Swept through the thickness, the factor carries into the solve."
             % (len(gc), len(uc), len(uc) / float(len(gc))), ha="center", fontsize=10)
    fig.subplots_adjust(top=0.845, bottom=0.17, wspace=0.08)
    return save(fig, os.path.join(out, "graded_vs_uniform.png"))


