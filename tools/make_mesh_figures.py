"""Comparison figures of the explicit transition mesh, written to docs/images/ as PNG.

Three figures, all built by running the repository's own code -- nothing is drawn by hand:

  transition_templates.png        the two templates themselves (mesh_transition/templates.py), 2->1 pair and 3->1
  transition_vs_unstructured.png  the same weld region coarsened by the templates and, for comparison, meshed
                                automatically by gmsh (quadrilateral recombination, the same sizes). Element count
                                and shape quality come out much the same; the structure does not
  graded_vs_uniform.png           a weld region graded away from the seam with the templates, against the same region
                                meshed at the weld size throughout: the element count the grading saves

Every shape number printed on the figures comes from `mesh_transition.quality` (quads) or from the same angle
definition applied to triangles, computed here at draw time.

Needs matplotlib and gmsh, which the pipeline itself does not: the figures are regenerated by hand, not in CI.

Usage: python tools/make_mesh_figures.py [out_dir]"""
import io
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from mesh_transition.mesh import Mesh, check_all  # noqa: E402
from mesh_transition.quality import corner_values, metrics  # noqa: E402
from mesh_transition.templates import strip, t2_pair, t3  # noqa: E402

OUT = os.path.join(ROOT, "docs", "images")
FINE, COARSE, GOOD, BAD, EDGE, TEXT, MUTED = "#dbeafe", "#eff6ff", "#dcfce7", "#fee2e2", "#1f2937", "#111827", "#6b7280"


# ---------------------------------------------------------------- shape quality, quads and triangles
def min_corner_sine(p):
    """Smallest sine of an interior angle. For a quadrilateral this is `quality.corner_jacobian`."""
    if len(p) == 4:
        return metrics(p)["corner_jacobian"]
    out = []
    for k in range(3):
        ax, ay = p[(k + 1) % 3][0] - p[k][0], p[(k + 1) % 3][1] - p[k][1]
        bx, by = p[(k - 1) % 3][0] - p[k][0], p[(k - 1) % 3][1] - p[k][1]
        la, lb = math.hypot(ax, ay), math.hypot(bx, by)
        out.append(abs(ax * by - ay * bx) / (la * lb) if la and lb else 0.0)
    return min(out)


def worst_corner_deg(p):
    """The interior angle of the corner with the smallest sine: the one that is closest to folded flat (180 deg)
    or closest to a sliver (0 deg). Reporting this angle and its sine keeps the two numbers consistent."""
    n = len(p)
    best = None
    for k in range(n):
        ax, ay = p[(k + 1) % n][0] - p[k][0], p[(k + 1) % n][1] - p[k][1]
        bx, by = p[(k - 1) % n][0] - p[k][0], p[(k - 1) % n][1] - p[k][1]
        la, lb = math.hypot(ax, ay), math.hypot(bx, by)
        if not (la and lb):
            continue
        sine = abs(ax * by - ay * bx) / (la * lb)
        ang = math.degrees(math.acos(max(-1.0, min(1.0, (ax * bx + ay * by) / (la * lb)))))
        if best is None or sine < best[0]:
            best = (sine, ang)
    return best[1] if best else 0.0


def stats(cells):
    """(elements, quads, triangles, min corner sine, min angle) of a list of corner-coordinate lists."""
    sines = [min_corner_sine(p) for p in cells]
    angles = [(min_corner_sine(p), worst_corner_deg(p)) for p in cells]
    return {"elements": len(cells), "quads": sum(1 for p in cells if len(p) == 4),
            "tris": sum(1 for p in cells if len(p) == 3),
            "min_sine": min(sines) if sines else 0.0,
            "worst_angle": min(angles)[1] if angles else 0.0}


def mesh_cells(m):
    return [list(m.corners(q)) for q in sorted(m.quads)]


# ---------------------------------------------------------------- drawing (matplotlib; figures only, not CI)
import matplotlib                                                                                 # noqa: E402
matplotlib.use("Agg")
import matplotlib.pyplot as plt                                                                   # noqa: E402
from matplotlib.collections import PolyCollection                                                 # noqa: E402

plt.rcParams.update({"font.family": "DejaVu Sans", "figure.dpi": 150, "savefig.dpi": 150,
                     "axes.titlesize": 12, "axes.titleweight": "bold"})


def draw_cells(ax, cells, fills=None, lw=1.0, title=None):
    ax.add_collection(PolyCollection(cells, facecolors=fills or [FINE] * len(cells), edgecolors=EDGE, linewidths=lw))
    xs = [p[0] for c in cells for p in c]
    ys = [p[1] for c in cells for p in c]
    pad = 0.04 * max(max(xs) - min(xs), max(ys) - min(ys))
    ax.set_xlim(min(xs) - pad, max(xs) + pad)
    ax.set_ylim(min(ys) - pad, max(ys) + pad)
    ax.set_aspect("equal", adjustable="datalim")   # keep the axes box fixed, so panel titles line up
    ax.axis("off")
    if title:
        ax.set_title(title, pad=8)


def fmt(st):
    """Two lines: what the elements are, then how good their worst corner is."""
    kinds = "%d quads + %d triangles" % (st["quads"], st["tris"]) if st["tris"] else "all quadrilateral"
    return ("%d elements   \u00b7   %s\nworst corner %.0f\u00b0   (sine %.3f)"
            % (st["elements"], kinds, st["worst_angle"], st["min_sine"]))


def caption(ax, text, size=8.5, y=-0.06):
    ax.text(0.5, y, text, transform=ax.transAxes, ha="center", va="top", fontsize=size, color=MUTED)


def save(fig, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fig.savefig(path, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    return path


# ---------------------------------------------------------------- figure 1: the two templates
def fig_templates(out):
    panels = [("2 \u2192 1, in pairs", t2_pair(),
               "4 fine edges \u2192 2 coarse. One 2\u21921 cell alone has an odd boundary edge count,\n"
               "so no all-quad filling of it exists: they only close in pairs."),
              ("3 \u2192 1", t3(), "3 fine edges \u2192 1 coarse, in a single cell.")]
    fig, axes = plt.subplots(1, 2, figsize=(9.4, 4.2))
    fig.suptitle("Explicit transition templates  (mesh_transition/templates.py)", fontsize=14, fontweight="bold",
                 y=0.99)
    fig.text(0.5, 0.885, "One row turns fine weld-side cells into coarse far-field cells. "
                         "Both are all-quadrilateral, with every node shared.",
             ha="center", fontsize=9.5, color=MUTED)
    for ax, (name, m, note) in zip(axes, panels):
        cells = mesh_cells(m)
        draw_cells(ax, cells, lw=1.4, title=name)
        caption(ax, fmt(stats(cells)) + "\n\n" + note, y=-0.04)
    fig.subplots_adjust(top=0.78, bottom=0.26, wspace=0.1)
    return save(fig, os.path.join(out, "transition_templates.png"))


# ---------------------------------------------------------------- region builders
def grid(x_edges, y_edges, m=None):
    m = m or Mesh()
    for j in range(len(y_edges) - 1):
        for i in range(len(x_edges) - 1):
            a = m.node(x_edges[i], y_edges[j])
            b = m.node(x_edges[i + 1], y_edges[j])
            cc = m.node(x_edges[i + 1], y_edges[j + 1])
            d = m.node(x_edges[i], y_edges[j + 1])
            m.quad(a, b, cc, d)
    return m


def graded_region(width=48.0, fine=2.0, bands=((2.0, 4.0), (4.0, 8.0)), fine_rows=2, coarse_rows=3):
    """Fine rows at the weld, two template rows doubling the cell size, coarse rows above."""
    m, y = Mesh(), 0.0
    size = fine
    for _ in range(fine_rows):
        grid([k * size for k in range(int(round(width / size)) + 1)], [y, y + size], m)
        y += size
    for small, big in bands:
        n_fine = int(round(width / small))
        row, _ = strip([2] * (n_fine // 2), h=small, height=big)
        # the template has its fine edges on top and its coarse edge below; here the fine mesh is at the weld,
        # at the bottom, so the row is mirrored in y (and the winding reversed with it, to stay counter-clockwise)
        for q in sorted(row.quads):
            p = [(px, y + (big - py)) for px, py in row.corners(q)][::-1]
            m.quad(*[m.node(*v) for v in p])
        y += big
        size = big
    for _ in range(coarse_rows):
        grid([k * size for k in range(int(round(width / size)) + 1)], [y, y + size], m)
        y += size
    chk = check_all(m)
    if not chk["ok"]:                      # a misplaced row leaves hanging nodes: the figure must not hide that
        raise ValueError("graded region is not a conforming mesh: %s"
                         % {k: (len(v) if isinstance(v, list) else v) for k, v in chk.items()
                            if k != "ok" and v not in (0, True, [])})
    return m, y


def gmsh_region(width=48.0, top=40.0, fine=2.0, coarse=8.0, grow=20.0):
    """The same region meshed automatically: gmsh, quadrilateral recombination, cells graded from `fine` at the weld
    edge to `coarse` away from it. A real automatic mesher doing the same job, so the comparison is not a straw man.

    gmsh is needed for this figure only, like matplotlib; the pipeline and CI do not use it."""
    import gmsh
    gmsh.initialize()
    try:
        gmsh.option.setNumber("General.Terminal", 0)
        gmsh.model.add("region")
        pts = [gmsh.model.geo.addPoint(x, y, 0) for x, y in ((0, 0), (width, 0), (width, top), (0, top))]
        lines_ = [gmsh.model.geo.addLine(pts[k], pts[(k + 1) % 4]) for k in range(4)]
        gmsh.model.geo.addPlaneSurface([gmsh.model.geo.addCurveLoop(lines_)])
        gmsh.model.geo.synchronize()
        d = gmsh.model.mesh.field.add("Distance")                 # distance from the weld edge
        gmsh.model.mesh.field.setNumbers(d, "CurvesList", [lines_[0]])
        t = gmsh.model.mesh.field.add("Threshold")
        gmsh.model.mesh.field.setNumber(t, "InField", d)
        gmsh.model.mesh.field.setNumber(t, "SizeMin", fine)
        gmsh.model.mesh.field.setNumber(t, "SizeMax", coarse)
        gmsh.model.mesh.field.setNumber(t, "DistMin", fine)
        gmsh.model.mesh.field.setNumber(t, "DistMax", grow)
        gmsh.model.mesh.field.setAsBackgroundMesh(t)
        for opt in ("Mesh.MeshSizeExtendFromBoundary", "Mesh.MeshSizeFromPoints", "Mesh.MeshSizeFromCurvature"):
            gmsh.option.setNumber(opt, 0)
        gmsh.option.setNumber("Mesh.RecombineAll", 1)
        gmsh.option.setNumber("Mesh.Algorithm", 8)                # frontal-Delaunay for quads
        gmsh.option.setNumber("Mesh.RecombinationAlgorithm", 2)
        gmsh.model.mesh.generate(2)
        tags, coords, _ = gmsh.model.mesh.getNodes()
        xy = {int(tag): (float(coords[3 * i]), float(coords[3 * i + 1])) for i, tag in enumerate(tags)}
        cells = []
        for etype, _, enodes in zip(*gmsh.model.mesh.getElements(2)):
            n = {2: 3, 3: 4}.get(etype)
            if n:
                ids = list(enodes)
                cells += [[xy[int(ids[k * n + j])] for j in range(n)] for k in range(len(ids) // n)]
        return cells
    finally:
        gmsh.finalize()


# ---------------------------------------------------------------- figure 2: by rule against automatic
def fig_vs_unstructured(out):
    g, top = graded_region()
    gc, ac = mesh_cells(g), gmsh_region(top=top)
    fig, axes = plt.subplots(1, 2, figsize=(9.6, 5.6))
    fig.suptitle("The same coarsening: laid out by rule, and meshed automatically",
                 fontsize=13.5, fontweight="bold", y=0.985)
    fig.text(0.5, 0.905, "48 \u00d7 %g mm, 2 mm cells along the weld (bottom edge), 8 mm in the far field." % top,
             ha="center", fontsize=9.5, color=MUTED)
    for ax, (title, cells) in zip(axes, (("Explicit templates  (this tool)", gc),
                                         ("Automatic mesher  (gmsh, quads)", ac))):
        draw_cells(ax, cells, lw=0.8, title=title)
        caption(ax, fmt(stats(cells)), y=-0.03, size=9)
    fig.text(0.5, 0.075, "Element count and shape quality come out much the same \u2014 an automatic mesher is good "
                         "at this. What differs is the structure:\non the left the rows are known before the mesh is "
                         "built, every vertical line lines up, a node can be demanded at a given\nposition, and the "
                         "same input always gives the same mesh, which is what makes two runs' solver input "
                         "comparable.",
             ha="center", fontsize=9, color=MUTED)
    fig.subplots_adjust(top=0.845, bottom=0.25, wspace=0.08)
    return save(fig, os.path.join(out, "transition_vs_unstructured.png"))


def fig_graded_vs_uniform(out):
    width, fine = 48.0, 2.0
    g, top = graded_region(width=width, fine=fine)
    u = grid([k * fine for k in range(int(round(width / fine)) + 1)],
             [k * fine for k in range(int(round(top / fine)) + 1)])
    gc, uc = mesh_cells(g), mesh_cells(u)
    fig, axes = plt.subplots(1, 2, figsize=(9.4, 5.2))
    fig.suptitle("The same weld region, graded away from the seam and meshed at the weld size throughout",
                 fontsize=13.5, fontweight="bold", y=0.985)
    fig.text(0.5, 0.93, "%g \u00d7 %g mm, %g mm cells along the weld (bottom edge); grading %g \u2192 %g \u2192 %g mm "
                        "through two template rows." % (width, top, fine, fine, 2 * fine, 4 * fine),
             ha="center", fontsize=9.5, color=MUTED)
    for ax, (title, cells) in zip(axes, (("Graded with the templates", gc), ("Uniform at the weld size", uc))):
        draw_cells(ax, cells, lw=0.7, title=title)
        caption(ax, fmt(stats(cells)), y=-0.04, size=9)
    fig.text(0.5, 0.045, "Same cell size along the weld, same region: %d elements against %d, a factor of %.1f in 2D. "
                         "Swept through the thickness, the factor carries into the solve."
             % (len(gc), len(uc), len(uc) / float(len(gc))), ha="center", fontsize=10)
    fig.subplots_adjust(top=0.845, bottom=0.17, wspace=0.08)
    return save(fig, os.path.join(out, "graded_vs_uniform.png"))


