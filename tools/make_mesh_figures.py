    panels = [("2 \u2192 1, in pairs", t2_pair(),
               "4 fine edges \u2192 2 coarse. One 2\u21921 cell alone has an odd boundary edge count,\n"
               "so no all-quad filling of it exists: they only close in pairs."),
              ("3 \u2192 1", t3(), "3 fine edges \u2192 1 coarse, in a single cell.")]
    fig, axes = plt.subplots(1, 2, figsize=(9.4, 4.2))
