OUT = os.path.join(ROOT, "docs", "images")
FINE, COARSE, GOOD, BAD, EDGE, TEXT, MUTED = "#dbeafe", "#eff6ff", "#dcfce7", "#fee2e2", "#1f2937", "#111827", "#6b7280"


# ---------------------------------------------------------------- shape quality, quads and triangles
def min_corner_sine(p):
    """Smallest sine of an interior angle. For a quadrilateral this is `quality.corner_jacobian`."""
    if len(p) == 4:
        return metrics(p)["corner_jacobian"]
    out = []
    for k in range(3):
        ax, ay = p[(k + 1) % 3][0] - p[k][0], p[(k + 1) % 3][1] - p[k][1]
        bx, by = p[(k - 1) % 3][0] - p[k][0], p[(k - 1) % 3][1] - p[k][1]
        la, lb = math.hypot(ax, ay), math.hypot(bx, by)
        out.append(abs(ax * by - ay * bx) / (la * lb) if la and lb else 0.0)
    return min(out)


def worst_corner_deg(p):
    """The interior angle of the corner with the smallest sine: the one that is closest to folded flat (180 deg)
    or closest to a sliver (0 deg). Reporting this angle and its sine keeps the two numbers consistent."""
    n = len(p)
    best = None
    for k in range(n):
        ax, ay = p[(k + 1) % n][0] - p[k][0], p[(k + 1) % n][1] - p[k][1]
        bx, by = p[(k - 1) % n][0] - p[k][0], p[(k - 1) % n][1] - p[k][1]
        la, lb = math.hypot(ax, ay), math.hypot(bx, by)
        if not (la and lb):
            continue
        sine = abs(ax * by - ay * bx) / (la * lb)
        ang = math.degrees(math.acos(max(-1.0, min(1.0, (ax * bx + ay * by) / (la * lb)))))
        if best is None or sine < best[0]:
            best = (sine, ang)
    return best[1] if best else 0.0


def stats(cells):
    """(elements, quads, triangles, min corner sine, min angle) of a list of corner-coordinate lists."""
    sines = [min_corner_sine(p) for p in cells]
    angles = [(min_corner_sine(p), worst_corner_deg(p)) for p in cells]
    return {"elements": len(cells), "quads": sum(1 for p in cells if len(p) == 4),
            "tris": sum(1 for p in cells if len(p) == 3),
            "min_sine": min(sines) if sines else 0.0,
            "worst_angle": min(angles)[1] if angles else 0.0}


def mesh_cells(m):
    return [list(m.corners(q)) for q in sorted(m.quads)]


# ---------------------------------------------------------------- drawing (matplotlib; figures only, not CI)
import matplotlib                                                                                 # noqa: E402
matplotlib.use("Agg")
import matplotlib.pyplot as plt                                                                   # noqa: E402
from matplotlib.collections import PolyCollection                                                 # noqa: E402

plt.rcParams.update({"font.family": "DejaVu Sans", "figure.dpi": 150, "savefig.dpi": 150,
                     "axes.titlesize": 12, "axes.titleweight": "bold"})


def draw_cells(ax, cells, fills=None, lw=1.0, title=None):
    ax.add_collection(PolyCollection(cells, facecolors=fills or [FINE] * len(cells), edgecolors=EDGE, linewidths=lw))
    xs = [p[0] for c in cells for p in c]
    ys = [p[1] for c in cells for p in c]
    pad = 0.04 * max(max(xs) - min(xs), max(ys) - min(ys))
    ax.set_xlim(min(xs) - pad, max(xs) + pad)
    ax.set_ylim(min(ys) - pad, max(ys) + pad)
    ax.set_aspect("equal", adjustable="datalim")   # keep the axes box fixed, so panel titles line up
    ax.axis("off")
    if title:
        ax.set_title(title, pad=8)


def fmt(st):
    """Two lines: what the elements are, then how good their worst corner is."""
    kinds = "%d quads + %d triangles" % (st["quads"], st["tris"]) if st["tris"] else "all quadrilateral"
    return ("%d elements   \u00b7   %s\nworst corner %.0f\u00b0   (sine %.3f)"
            % (st["elements"], kinds, st["worst_angle"], st["min_sine"]))


def caption(ax, text, size=8.5, y=-0.06):
    ax.text(0.5, y, text, transform=ax.transAxes, ha="center", va="top", fontsize=size, color=MUTED)


def save(fig, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fig.savefig(path, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    return path


