# -*- coding: utf-8 -*-
"""Bake the default watermark text into build/watermark_bitmap.py.

The label build/watermark.py puts beside the part is made of pixels. Rendering them from a font at build time would
make the label depend on Pillow, on a CJK font being installed, and on how that FreeType version rasterises it -- so
the same case could get a different label on another machine. The default text is therefore rasterised once, here,
and stored as hex rows; build/watermark.py decodes it without any font. A case that asks for other text renders it
with Pillow at build time.

Needs Pillow and a CJK font, which the pipeline itself does not: the bitmap is regenerated by hand, not in CI.

Usage: python tools/make_watermark_bitmap.py [font file]"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "build"))
from watermark import DEFAULT_LINES, PX_PER_LINE, render_bitmap  # noqa: E402

OUT = os.path.join(ROOT, "build", "watermark_bitmap.py")


def main():
    font = sys.argv[1] if len(sys.argv) > 1 else None
    rows, font_used = render_bitmap(DEFAULT_LINES, font)
    width = len(rows[0])
    hexrows = []
    for r in rows:
        bits = "".join("1" if v else "0" for v in r)
        bits += "0" * (-len(bits) % 4)
        hexrows.append("%0*x" % (len(bits) // 4, int(bits, 2)))
    body = ",\n".join('    "%s"' % h for h in hexrows)
    text = ('# -*- coding: utf-8 -*-\n'
            '"""Generated by tools/make_watermark_bitmap.py -- do not edit. The default watermark text as a bitmap,\n'
            'one hex string per pixel row, top row first, most significant bit leftmost."""\n'
            'LINES = %r\n'
            'PX_PER_LINE = %d\n'
            'WIDTH = %d\n'
            'FONT = %r\n'
            'ROWS = [\n%s,\n]\n') % (list(DEFAULT_LINES), PX_PER_LINE, width, os.path.basename(font_used), body)
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print("%s: %d x %d px from %s" % (OUT, width, len(rows), font_used))


if __name__ == "__main__":
    main()
